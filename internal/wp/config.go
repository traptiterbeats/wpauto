package wp

import (
	"fmt"
	"strings"
)

// DBConfig is what wp-config.php needs.
type DBConfig struct {
	Name, User, Pass, Host, TablePrefix string
}

func phpString(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

// Config returns a complete wp-config.php with fresh salts.
func Config(db DBConfig) string {
	if db.Host == "" {
		db.Host = "localhost"
	}
	if db.TablePrefix == "" {
		db.TablePrefix = "wp_"
	}
	var b strings.Builder
	b.WriteString("<?php\n/** Generated by wpauto. */\n\n")
	for _, kv := range [][2]string{{"DB_NAME", db.Name}, {"DB_USER", db.User}, {"DB_PASSWORD", db.Pass}, {"DB_HOST", db.Host},
		{"DB_CHARSET", "utf8mb4"}, {"DB_COLLATE", ""}} {
		fmt.Fprintf(&b, "define( '%s', %s );\n", kv[0], phpString(kv[1]))
	}
	b.WriteString("\n")
	for _, k := range []string{"AUTH_KEY", "SECURE_AUTH_KEY", "LOGGED_IN_KEY", "NONCE_KEY", "AUTH_SALT", "SECURE_AUTH_SALT", "LOGGED_IN_SALT", "NONCE_SALT"} {
		fmt.Fprintf(&b, "define( '%s', %s );\n", k, phpString(RandString(64, Salt)))
	}
	fmt.Fprintf(&b, "\n$table_prefix = %s;\n\n", phpString(db.TablePrefix))
	b.WriteString("define( 'WP_DEBUG', false );\ndefine( 'DISALLOW_FILE_EDIT', true );\ndefine( 'FS_METHOD', 'direct' );\n\n")
	b.WriteString("if ( ! defined( 'ABSPATH' ) ) {\n\tdefine( 'ABSPATH', __DIR__ . '/' );\n}\n\nrequire_once ABSPATH . 'wp-settings.php';\n")
	return b.String()
}

// Htaccess returns WordPress's standard rewrite rules for a site served under base ("/" or "/blog/").
func Htaccess(base string) string {
	if !strings.HasPrefix(base, "/") {
		base = "/" + base
	}
	if !strings.HasSuffix(base, "/") {
		base += "/"
	}
	return "# BEGIN WordPress\n<IfModule mod_rewrite.c>\nRewriteEngine On\nRewriteRule .* - [E=HTTP_AUTHORIZATION:%{HTTP:Authorization}]\n" +
		"RewriteBase " + base + "\nRewriteRule ^index\\.php$ - [L]\nRewriteCond %{REQUEST_FILENAME} !-f\nRewriteCond %{REQUEST_FILENAME} !-d\n" +
		"RewriteRule . " + base + "index.php [L]\n</IfModule>\n# END WordPress\n"
}
